const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id);
const opt = re => S.dialog.all.find(o => re.test(o.label));

ok(Object.keys(G.QUESTS).length >= 11, Object.keys(G.QUESTS).length + ' quests defined');
G.enterZone('outpost', 610, 440);
ok(Object.values(G.save.quests).every(v => v === 'none'), 'no quests at the start');
G.TALK.talkVendor(npc('v_trade_outpost'));
ok(opt(/Herbs for the Stall/) && !opt(/Collect/), 'Hale offers Herbs for the Stall');
opt(/Herbs/).fn(); opt(/Accept/).fn();
ok(G.save.quests.herbs === 'active', 'herb quest accepted'); G.save.quests.tour_outpost = 'done';
ok(G.questMarker(npc('v_trade_outpost')) === false, 'no marker on Pell until the herbs are gathered');
G.TALK.talkVendor(npc('v_trade_outpost')); ok(opt(/Healing Herb 0\/3/), 'Pell shows progress');
G.giveItem('healing_herb', 3, true);
ok(G.questMarker(npc('v_trade_outpost')), 'marker returns when the herbs are ready');
G.TALK.talkVendor(npc('v_trade_outpost')); opt(/Report/).fn(); const gil0 = G.save.gil; opt(/Collect/).fn();
ok(G.save.quests.herbs === 'done' && G.invCount('healing_herb') === 0 && G.invCount('pickaxe') === 1 && G.invCount('hatchet') === 1 && G.save.gil === gil0 + 100, 'herbs handed in: tools and gil received');
G.TALK.talkBrann(npc('brann'));
ok(!opt(/Night Wings/), 'Night Wings needs level 2');
G.save.jobs.WAR.lv = 2; G.refreshPlayer(true);
G.TALK.talkBrann(npc('brann')); opt(/Night Wings/).fn(); opt(/Accept/).fn();
ok(G.save.quests.nightwings === 'active' && G.save.qprog.nightwings === 0, 'Night Wings accepted with a kill counter');
G.enterZone('hollow', 200, 1100); run(1); S.mobs = []; S.spawnAt = [];
for (let k = 0; k < 4; k++) { const b = G.buildMob('bat', 1, 260, 1100, 0); S.mobs.push(b); b.enmity.set(P(), 5); G.onKO(b, P()); }
ok(G.save.qprog.nightwings === 4 && G.questComplete('nightwings'), 'four bat kills complete the objective');
const w = G.buildMob('worm', 1, 260, 1100, 0); S.mobs.push(w); w.enmity.set(P(), 5); G.onKO(w, P());
ok(G.save.qprog.nightwings === 4, 'other monsters do not count');
G.enterZone('outpost', 610, 440);
G.TALK.talkBrann(npc('brann')); opt(/Report/).fn(); opt(/Collect/).fn();
ok(G.save.quests.nightwings === 'done', 'Night Wings handed in');
G.TALK.talkRhea(npc('rhea')); ok(!opt(/Bones/), 'Rhea holds the bones quest until Pouches is done and level 4');
G.save.quests.pouches = 'done'; G.save.jobs.WAR.lv = 4; G.refreshPlayer(true);
G.TALK.talkRhea(npc('rhea')); ok(opt(/Bones in the Ruins/) && !opt(/handle him/), 'Rhea offers Bones in the Ruins, not the Chieftain yet');
opt(/Bones/).fn(); opt(/Accept/).fn();
G.save.qprog.bones = 5; G.save.jobs.WAR.lv = 7; G.refreshPlayer(true);
G.TALK.talkRhea(npc('rhea')); opt(/Report/).fn(); opt(/Collect/).fn();
ok(G.save.quests.bones === 'done' && G.invCount('potion') >= 3, 'bones quest done, potions received');
G.TALK.talkRhea(npc('rhea')); ok(opt(/handle him/) && opt(/Grimtooth/), 'at 7 Rhea offers the Chieftain and Grimtooth bounty');
opt(/Grimtooth/).fn(); opt(/Accept/).fn();
G.enterZone('hollow', 200, 1100); run(1); S.mobs = []; S.spawnAt = [];
const gt = G.buildMob('grimtooth', 6, 260, 1100, 0); S.mobs.push(gt); gt.enmity.set(P(), 5); G.onKO(gt, P());
ok(G.questComplete('grimtooth'), 'defeating Grimtooth completes the bounty');
G.save.quests.chieftain = 'done'; G.save.jobs.WAR.lv = 8; G.refreshPlayer(true);
ok(G.questOfferable('warden'), "The Warden's Vigil opens after the Chieftain at level 8");
const txt = G.exportSaveText(); const d = G.importSaveText(txt);
ok(d && d.qprog.nightwings === 4 && d.quests.herbs === 'done', 'quest progress survives save files');
G.openModal('quests'); ok(/Night Wings/.test(document.getElementById('mBody').innerHTML) && !/Warden/.test(document.getElementById('mBody').innerHTML), 'journal lists accepted quests only'); G.closeModal();
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
