const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
G.enterZone('outpost'); run(0.5);
const rules = G.JOB_REQ;
const expect = { MNK: 'WAR5', RDM: 'BLM5,WHM5', RNG: 'MNK5,THF5', SCH: 'WHM10', COR: 'SCH5,THF5', DRK: 'BLM5,WAR5', GEO: 'MNK5', BST: 'GEO5', NIN: 'THF5,WAR5', PLD: 'WAR5,WHM5', DNC: 'BLM5,THF5', BRD: 'THF5,WHM5', DRG: 'NIN5,THF5', SAM: 'WAR10', SMN: 'BLM10,RDM10,WHM10', BLU: 'BLM10,WHM10', RUN: 'BLM10,WAR10', PUP: 'BLM10,RDM10' };
const flat = j => Object.entries(rules[j]).map(([k, v]) => k + v).sort().join(',');
ok(Object.keys(expect).every(j => flat(j) === expect[j]) && Object.keys(rules).length === 18, 'the unlock table matches your list (18 jobs)');
ok(Object.keys(G.JOBS).filter(j => !['WAR', 'WHM', 'BLM', 'THF'].includes(j)).every(j => rules[j]), 'every non-starting job has a rule');
ok(Object.keys(rules).every(j => G.JOB_FLAVOUR[j]), 'every unlockable job has a popup line');
const fresh = () => { const s = G.newSave(); s.jobsUnlocked = {}; return s; };
const sv = fresh();
ok(G.checkJobUnlocksIn(sv).length === 0, 'a new character unlocks nothing');
sv.jobs.WAR.lv = 5; let got = G.checkJobUnlocksIn(sv);
ok(got.sort().join() === 'MNK', 'Warrior 5 opens Monk');
sv.jobs.WHM.lv = 5; got = G.checkJobUnlocksIn(sv);
ok(got.sort().join() === 'PLD', 'adding White Mage 5 opens Paladin');
sv.jobs.BLM.lv = 5; got = G.checkJobUnlocksIn(sv);
ok(got.sort().join() === 'DRK,RDM', 'Black Mage 5 opens Dark Knight and Red Mage');
sv.jobs.THF.lv = 5; sv.jobs.MNK.lv = 5; got = G.checkJobUnlocksIn(sv);
ok(got.sort().join() === 'BRD,DNC,GEO,NIN,RNG', 'Thief 5 and Monk 5 open Bard, Dancer, Geomancer, Ninja and Ranger');
sv.jobs.NIN.lv = 5; sv.jobs.GEO.lv = 5; ok(G.checkJobUnlocksIn(sv).sort().join() === 'BST,DRG', 'Ninja 5 opens Dragoon and Geomancer 5 opens Beastmaster');
sv.jobs.WHM.lv = 10; sv.jobs.BLM.lv = 10; sv.jobs.WAR.lv = 10; got = G.checkJobUnlocksIn(sv);
ok(got.sort().join() === 'BLU,RUN,SAM,SCH', 'level 10 opens Blue Mage, Rune Fencer, Samurai and Scholar');
sv.jobs.RDM.lv = 10; got = G.checkJobUnlocksIn(sv);
ok(got.sort().join() === 'PUP,SMN', 'Red Mage 10 opens Puppetmaster and Summoner');
ok(G.checkJobUnlocksIn(sv).length === 0, 'nothing opens twice');
sv.jobs.WAR.lv = 1; ok(G.jobReqMet(sv, 'SAM') === false && sv.jobsUnlocked.SAM === true, 'levelling down never takes a job back');
G.save.jobsUnlocked = {}; for (const j in G.save.jobs) G.save.jobs[j].lv = 1; G.save.jobPopups = [];
ok(G.jobUnlocked('THF') && !G.jobUnlocked('MNK'), 'Thief starts open, Monk locked');
G.save.jobs.WAR.xp = 0; G.save.jobs.WAR.lv = 4; G.save.mainJob = 'WAR'; G.refreshPlayer(true);
G.gainXp(1e6);
ok(G.save.jobs.WAR.lv >= 5 && G.jobUnlocked('MNK') && G.save.jobPopups.includes('MNK'), 'levelling Warrior to 5 unlocks Monk and queues the popup');
const q0 = G.save.jobPopups.length;
S.modal = 'party';
G.jobPopupTick(); ok(G.save.jobPopups.length === q0, 'the popup waits while a menu is open');
S.modal = null;
const hint = G.jobProgressHint();
ok(typeof hint === 'string' && hint.length > 10 && !/Thief|Monk|Warrior|Paladin/.test(hint), 'Tobin\'s hint is vague and names no job');
const old = JSON.parse(JSON.stringify(G.save)); old.jobsUnlocked = { PLD: true }; old.jobs.WAR.lv = 10;
const nv = G.normalizeSave(old);
ok(nv.jobsUnlocked.PLD && nv.jobsUnlocked.SAM && nv.jobsUnlocked.MNK, 'an old save keeps its quest jobs and gains the ones it already qualifies for');
const t = JSON.parse(JSON.stringify(G.save)); t.quests.mnk = 'done'; t.jobsUnlocked = {}; for (const j in t.jobs) t.jobs[j].lv = 1;
ok(!G.normalizeSave(t).jobsUnlocked.MNK, 'finishing the old Monk quest no longer opens the job');
G.save.quests.thf = 'none'; G.save.quests.mnk = 'none'; G.save.jobs.WAR.lv = 20; S.zoneCooldown = 0; G.save.jobsUnlocked.PLD = false; G.save.jobsUnlocked.MNK = false;
ok(!G.questOfferable('mnk') && !G.questOfferable('pld'), 'Tobin no longer offers the old job quests');
G.save.jobsUnlocked = {};
let locked = 0; for (const j in G.JOBS) if (!G.jobUnlocked(j)) locked++;
G.setJob('SMN', null);
ok(G.save.mainJob !== 'SMN', 'you cannot switch to a locked job');
console.log(fails ? fails + ' FAILED' : 'ALL PASS'); process.exit(fails ? 1 : 0);
