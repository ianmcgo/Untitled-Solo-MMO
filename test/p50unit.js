const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
G.enterZone('outpost', G.ZONES.outpost.start.x, G.ZONES.outpost.start.y); run(0.3);
const id = G.mercPool ? null : null;
const mid = Object.keys(G.MERCS).find(k => G.mercAvailable(k));
G.save.gil = 99999; G.hireMerc(mid); run(0.3);
const m = S.party.find(p => p.mercId === mid);
ok(!!m, 'a hireling joined the party');
G.enterZone('hollow', 300, 300); run(0.3);
const m2 = S.party.find(p => p.mercId === mid);
m2.x = 500; m2.y = 520; m2.alive = false; m2.hp = 0; m2.koUntil = Date.now() + 3600000;
G.save.mercBodies = { [mid]: { zone: 'hollow', x: 500, y: 520, until: m2.koUntil } };
G.save.mercDown = { [mid]: m2.koUntil };
G.enterZone('outpost', G.ZONES.outpost.start.x, G.ZONES.outpost.start.y); run(0.3);
ok(!S.party.some(p => p.mercId === mid), 'a fallen hireling does not follow you to town');
ok(G.save.hired.includes(mid) && G.save.mercBodies[mid], 'the hireling stays hired and the body is remembered');
G.enterZone('hollow', 300, 300); run(0.3);
const b = S.party.find(p => p.mercId === mid);
ok(b && !b.alive && Math.abs(b.x - 500) < 2 && Math.abs(b.y - 520) < 2, 'the body is still where it fell');
G.save.inv = G.save.inv || {}; 
P().x = 480; P().y = 500; G.player.target = b; S.itemReadyAt = 0;
G.save.bag ? 0 : 0;
const before = G.invCount('phoenix_down');
G.giveItem('phoenix_down', 2);
G.useItem('phoenix_down'); run(0.2);
ok(b.alive && b.hp >= b.maxHp * 0.45, 'a Phoenix Down revives the hireling');
ok(!G.save.mercBodies[mid], 'the body record is cleared');
P().alive = false; P().hp = 0; S.ko = true; P().koUntil = Date.now() + 3600000; S.itemReadyAt = 0;
G.useItem('phoenix_down'); run(0.2);
ok(P().alive && !S.ko, 'a KO\'d player can use a Phoenix Down on themselves');
ok(G.invCount('phoenix_down') === before, 'both feathers were consumed');
console.log(fails ? "FAILED " + fails : "ALL PASSED");
