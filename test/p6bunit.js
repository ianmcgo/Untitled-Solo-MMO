const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id);
const opt = re => S.dialog.all.find(o => re.test(o.label));

ok(G.FEATURES.crafting && G.FEATURES.gathering, 'crafting and gathering are switched on');
G.enterZone('hollow', 200, 1100); run(0.5);
const points = S.npcs.filter(n => n.prop === 'gather');
ok(points.length === 9 && ['mining', 'logging', 'harvesting'].every(t => points.filter(p => p.gtype === t).length === 3), 'Rocky Hollow has three points of each gathering type');
const mine = points.find(p => p.gtype === 'mining');
P().x = mine.x; P().y = mine.y + 30;
const n0 = H.alllog.length; G.doGather(mine);
ok(H.alllog.slice(n0).some(l => /need a Pickaxe/.test(l)), 'mining needs a pickaxe');
G.giveItem('pickaxe', 1, true);
const saved = Math.random; Math.random = () => 0.01;
G.doGather(mine);
ok(G.invCount('copper_ore') === 1 && G.save.gatherSkill.mining > 0, 'mining with a pickaxe yields ore and raises skill');
Math.random = () => 0.99; const uses = mine.uses; G.giveItem('pickaxe', 1, true);
G.doGather(mine);
ok(G.invCount('pickaxe') >= 1 && mine.uses === uses - 1, 'a bad roll finds nothing and uses the point');
Math.random = () => 0.2;
while (!mine.gone) { G.giveItem('pickaxe', 1, true); G.doGather(mine); }
ok(mine.gone && S.gatherAt.filter(r => r.type === 'mining').length === 1, 'an exhausted point retires and schedules a new one');
S.gatherAt.forEach(r => r.at = Date.now() - 1); run(1);
ok(S.npcs.filter(n => n.prop === 'gather' && n.gtype === 'mining' && !n.gone).length === 3, 'a replacement point appears elsewhere after the timer');
Math.random = saved;

const r = G.RECIPES.find(x => x.id === 'r_bronze_ingot');
ok(G.canSynth(r) !== '', 'cannot synthesize without materials');
G.giveItem('fire_crystal', 2, true); G.giveItem('copper_ore', 4, true); const ore0 = G.invCount('copper_ore');
ok(G.synthChance(r) === 65, 'base success is 65% at equal skill');
const sv = Math.random; Math.random = () => 0.1;
ok(G.startSynth('r_bronze_ingot') === '' && P().synth, 'synthesis starts');
run(1.5); ok(P().synth, 'synthesis takes about 3 s'); run(2);
ok(!P().synth && G.invCount('bronze_ingot') === 1 && G.invCount('fire_crystal') === 1 && G.invCount('copper_ore') === ore0 - 2, 'success consumes the crystal and ingredients and makes an ingot');
ok(G.craftSkill('smithing') > 0, 'smithing skill rose');
Math.random = () => 0.99;
G.startSynth('r_bronze_ingot'); run(3.5);
ok(!P().synth && G.invCount('bronze_ingot') === 1 && G.invCount('fire_crystal') === 0, 'a failed synthesis breaks the crystal and keeps the ingot count');
Math.random = sv;
G.giveItem('fire_crystal', 1, true); G.startSynth('r_bronze_ingot');
const m = G.buildMob('goblin', 1, P().x + 20, P().y, 0); S.mobs.push(m); m.state = 'combat'; m.enmity.set(P(), 10); run(0.5);
ok(!P().synth, 'being attacked interrupts synthesis');
S.mobs = [];

G.enterZone('outpost', 610, 440); run(0.2);
G.save.gil = 5000; G.openModal('furnishings'); G.buy('flowerpot'); G.buy('herb_seeds'); G.buy('wildgrass_seeds'); G.closeModal();
ok(G.invCount('flowerpot') === 1 && G.invCount('herb_seeds') === 1, 'Odette sells flowerpots and seeds');
G.enterZone('residence', 200, 250); run(0.3);
G.TALK.talkPip(npc('pip')); ok(opt(/Green Thumb/), 'Pip offers Green Thumb'); opt(/Green Thumb/).fn(); opt(/Accept/).fn();
ok(G.placeFurniture('flowerpot', 6, 5, 0) === '', 'placed the flowerpot');
const pi = G.save.furniture.findIndex(f => f.id === 'flowerpot');
ok(G.plantSeed(pi, 'herb_seeds') === '' && G.save.gardens[pi] && G.save.gardens[pi].stage === 0 && G.invCount('herb_seeds') === 0, 'planted herb seeds');
ok(G.removeFurniture(pi) !== '', 'cannot pack away a planted pot');
G.save.gardens[pi].since = Date.now() - 20 * 60 * 1000; G.gardenTick();
ok(G.save.gardens[pi].stage === 0, 'a dry plant does not grow');
ok(G.waterGarden(pi) === '' && G.waterGarden(pi) !== '', 'watering once, not twice');
G.giveItem('earth_crystal', 1, true);
ok(G.feedGarden(pi, 'earth_crystal') === '' && G.save.gardens[pi].crystal === 'earth' && G.invCount('earth_crystal') === 0, 'fed an earth crystal');
for (let s = 0; s < 3; s++) { G.save.gardens[pi].watered = true; G.save.gardens[pi].since = Date.now() - 11 * 60 * 1000; G.gardenTick(); }
ok(G.save.gardens[pi].stage === 3, 'three watered 10-minute stages reach harvest');
ok(G.harvestGarden(pi) === '' && G.invCount('healing_herb') >= 5 && G.invCount('healing_herb') <= 8 && !G.save.gardens[pi], 'harvest gives 5–8 herbs with the matching crystal bonus');
ok(G.questComplete('greenthumb'), 'Green Thumb completes on the first harvest');
G.TALK.talkPip(npc('pip')); opt(/Report/).fn(); opt(/Collect/).fn();
ok(G.save.quests.greenthumb === 'done' && G.invCount('wildgrass_seeds') === 3, 'Pip rewards wildgrass seeds');
const txt = G.exportSaveText(); const d = G.importSaveText(txt);
ok(d && d.crafts.smithing > 0 && d.gatherSkill.mining > 0 && d.harvests === 1, 'craft, gather skills and harvests survive save files');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
