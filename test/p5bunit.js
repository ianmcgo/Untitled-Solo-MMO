const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
G.save.spells = Object.keys(G.SPELLS);
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id);

G.enterZone('outpost', 610, 440);
ok(!G.jobUnlocked('PLD') && !G.jobUnlocked('RDM') && G.jobUnlocked('WAR'), 'advanced jobs start locked');
G.setJob('PLD', null); ok(G.save.mainJob === 'WAR', 'cannot set a locked job');
ok(!G.mercAvailable('dorn') && !G.mercAvailable('lisette'), 'Dorn and Lisette are unavailable while locked');
G.TALK.talkTobin(npc('tobin')); ok(!S.dialog.all.some(o => /Paladin/.test(o.label)), 'Tobin keeps quiet about advanced jobs below level 6');
G.save.jobs.WAR.lv = 6; G.refreshPlayer(true);
G.TALK.talkTobin(npc('tobin'));
const askP = S.dialog.all.find(o => /Paladin/.test(o.label)); ok(!!askP, 'at level 6 Tobin offers the Paladin oath');
askP.fn(); S.dialog.all.find(o => o.label === 'Accept').fn();
ok(G.save.quests.pld === 'active', 'Paladin quest accepted');
G.TALK.talkTobin(npc('tobin')); ok(!S.dialog.all.some(o => /oath/.test(o.label)), 'no turn-in without the items');
G.giveItem('bone_chip', 2, true); G.giveItem('iron_ore', 1, true);
G.TALK.talkTobin(npc('tobin')); S.dialog.all.find(o => /oath/.test(o.label)).fn();
ok(G.save.quests.pld === 'done' && G.jobUnlocked('PLD') && G.invCount('bone_chip') === 0, 'oath taken: Paladin unlocked, items consumed');
ok(G.mercAvailable('dorn') && !G.mercAvailable('lisette'), 'Dorn unlocks with Paladin; Lisette still locked');
G.TALK.talkTobin(npc('tobin')); S.dialog.all.find(o => /Red Mage/.test(o.label)).fn(); S.dialog.all.find(o => o.label === 'Accept').fn();
G.giveItem('worm_silk', 2, true); G.giveItem('fire_crystal', 1, true); G.giveItem('water_crystal', 1, true);
G.TALK.talkTobin(npc('tobin')); S.dialog.all.find(o => /dye/.test(o.label)).fn();
ok(G.jobUnlocked('RDM') && G.mercAvailable('lisette'), 'Red Mage unlocked, Lisette available');
G.closeModal();
G.setJob('PLD', null); ok(G.save.mainJob === 'PLD' && P().job === 'PLD', 'switched to Paladin');
G.save.jobs.PLD.lv = 7; G.refreshPlayer(true);
const acts = G.actionList(P()).map(a => a.id);
ok(acts.includes('sentinel') && acts.includes('shield_bash') && acts.includes('cure') && acts.includes('banish') && !acts.includes('provoke'), 'Paladin 7 knows Sentinel, Shield Bash, Cure, Banish (' + acts.join(',') + ')');
G.save.gil = 5000; G.giveItem('lauan_shield', 1, true); G.equip('lauan_shield'); ok(G.save.gear.sub === 'lauan_shield', 'kite shield equips in the sub slot');
G.setJob('RDM', null); G.save.jobs.RDM.lv = 8; G.refreshPlayer(true);
const racts = G.actionList(P()).map(a => a.id);
ok(['dia', 'cure', 'stone', 'poison', 'paralyze', 'protect', 'blind', 'convert'].every(x => racts.includes(x)), 'Red Mage 8 knows Dia, Cure, Stone, Poison, Paralyze, Protect, Blind, Convert');
ok(G.skillCap(P(), 'enfeebling') > 0 && G.skillCap(P(), 'sword') > G.skillCap(P(), 'club'), 'RDM skill caps: enfeebling exists, sword B over club D');

G.enterZone('hollow', 200, 1100); run(1); S.mobs = []; S.spawnAt = [];
const m = G.buildMob('goblin', 6, 240, 1100, 0); S.mobs.push(m);
const d0 = G.stat(m, 'def');
G.save.jobs.RDM.lv = 13; G.refreshPlayer(true); if (!G.save.spells.includes('slow')) G.save.spells.push('slow');
P().mp = 200; P().target = m; const sv1 = Math.random; Math.random = () => 0.2;
G.playerAct({ kind: 'ma', id: 'slow' }); run(2.5); Math.random = sv1;
ok(!!m.buffs.slow, 'Slow lands (' + Object.keys(m.buffs) + ')');
const baseDelay = m.delay; m.state = 'combat'; m.enmity.set(P(), 50); m.swingTimer = 0; m.x = P().x + 20; m.y = P().y;
run(0.1);
ok(Math.abs(m.swingTimer - baseDelay * 1.25) < 0.2 || m.swingTimer > baseDelay, 'slowed monsters swing slower (' + m.swingTimer.toFixed(2) + ' vs ' + baseDelay + ')');
P().recasts = {}; P().mp = 200; const sv2 = Math.random; Math.random = () => 0.2;
G.playerAct({ kind: 'ma', id: 'paralyze' }); run(3.4); Math.random = sv2;
ok(!!m.buffs.paralyze, 'Paralyze lands');
const saved = Math.random; Math.random = () => 0.1; const n0 = H.alllog.length; G.swing(m, P()); Math.random = saved;
ok(H.alllog.slice(n0).some(l => /paralyzed/.test(l)), 'a paralyzed monster can lose its swing');
G.setJob('PLD', null); G.refreshPlayer(true); P().mp = 100; P().hp = P().maxHp; P().recasts = {};
const dBefore = G.stat(P(), 'def');
G.playerAct({ kind: 'ja', id: 'sentinel' });
ok(P().buffs.sentinel && G.stat(P(), 'def') > dBefore * 1.4, 'Sentinel raises defense by 50%');
m.enmity.set(P(), 100); P().mp = 100; P().target = m; const mh0 = m.hp; G.playerAct({ kind: 'ma', id: 'banish' }); run(2.6);
ok(m.hp < mh0, 'Banish hurts the monster');
P().recasts = {}; m.readying = { t: 1, target: P(), start: S.time }; m.x = P().x + 20;
G.playerAct({ kind: 'ja', id: 'shield_bash' });
ok(!m.readying, 'Shield Bash interrupts a readied TP move');
G.setJob('RDM', null); G.refreshPlayer(true); P().hp = Math.round(P().maxHp * 0.9); P().mp = 3; P().recasts = {};
const hp0 = P().hp; G.playerAct({ kind: 'ja', id: 'convert' });
ok(P().mp === Math.min(P().maxMp, hp0) && P().hp === 3, 'Convert swaps HP and MP (capped at max MP)');

G.save.gil = 5000; G.hireMerc('dorn'); G.hireMerc('lisette');
const dorn = S.party.find(p => p.mercId === 'dorn'), lis = S.party.find(p => p.mercId === 'lisette');
ok(dorn && dorn.job === 'PLD' && dorn.role === 'tank' && lis && lis.job === 'RDM', 'Dorn and Lisette hired with their jobs');
ok(dorn.gear.sub === 'lauan_shield' && lis.gear.body === 'hume_tunic' || lis.gear.body === 'linen_robe', 'companions get job gear');
S.mobs = []; const m2 = G.buildMob('goblin', 6, P().x + 40, P().y, 0); S.mobs.push(m2); m2.state = 'combat'; m2.enmity.set(P(), 10);
P().engaged = true; P().attackTarget = m2; P().target = m2;
run(12);
ok(m2.buffs.poison || m2.buffs.blight || m2.buffs.dia || m2.buffs.paralyze, 'companions use their new spells in a fight (' + Object.keys(m2.buffs) + ')');
const txt = G.exportSaveText(); const d = G.importSaveText(txt);
ok(d && d.jobsUnlocked.PLD && d.jobsUnlocked.RDM, 'job unlocks survive save files');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
