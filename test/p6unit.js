const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id);
const opt = re => S.dialog.all.find(o => re.test(o.label));
const setHour = h => { const v = G.vana(); let d = h - v.hour - v.minute / 60; if (d < 0) d += 24; S.timeShift += d * 3600000 / 25; };

setHour(10);
G.enterZone('outpost', 610, 440); run(0.2);
ok(S.zone.exits.some(e => e.to === 'residence' && e.kind === 'door'), 'the Outpost has a door to your residence');
ok(npc('odette') && G.ZONES.outpost.npcs.filter(n => n.sleep).length === 7, 'Odette is in town and seven townsfolk have bed times');
ok(S.npcs.filter(n => n.sleep).every(n => !n.away), 'everyone is out at 10:00');
G.TALK.talkOdette(npc('odette')); ok(opt(/Make It Home/), 'Odette offers Make It Home'); opt(/Make It Home/).fn(); opt(/Accept/).fn();
G.closeModal();
G.save.gil = 5000; G.openModal('furnishings'); G.buy('wooden_chair'); G.buy('wooden_chair'); G.buy('storage_chest'); G.buy('round_rug'); G.closeModal();
ok(G.invCount('wooden_chair') === 2 && G.invCount('storage_chest') === 1, 'bought furniture from Odette');
setHour(22.5); run(0.2);
ok(npc('tobin').away || npc('tobin').heading, 'Tobin (bed at 20:00) has gone home by 22:30');
ok(!npc('brann').away && !npc('brann').heading, 'Brann (bed at 23:00) is still out at 22:30');
run(40);
ok(npc('tobin').away && npc('pell').away && npc('rhea').away, 'by now Tobin, Pell and Rhea are indoors');
P().x = npc('tobin').x; P().y = npc('tobin').y + 30;
ok(G.nearNpc() !== npc('tobin'), 'you cannot talk to an NPC who is indoors');
setHour(8); run(30);
ok(S.npcs.filter(n => n.sleep).every(n => !n.away), 'everyone comes back out in the morning');
ok(G.dist(npc('tobin'), npc('tobin').post) < 60, 'Tobin walks back to his post (' + Math.round(G.dist(npc('tobin'), npc('tobin').post)) + ' px)');

G.enterZone('residence', 200, 250); run(0.5);
ok(S.zoneId === 'residence' && npc('pip') && npc('pip').prop === 'nubbin', 'the residence has Pip');
G.TALK.talkPip(npc('pip')); ok(opt(/Storage/) && opt(/Arrange/), 'Pip offers storage and arranging'); G.closeModal();
ok(G.storageCap() === 20, 'base storage is 20 slots');
ok(!G.placeFurniture('wooden_chair', 0, 0, 0) === false && G.placeFurniture('wooden_chair', 0, 0, 0) !== '', 'cannot place on a blocked tile');
ok(G.placeFurniture('wooden_chair', 3, 3, 0) === '' && G.save.furniture.length === 1 && G.invCount('wooden_chair') === 1, 'placed a chair');
ok(G.placeFurniture('wooden_chair', 3, 3, 0) !== '', 'cannot stack two chairs on one tile');
ok(G.placeFurniture('round_rug', 3, 3, 0) === '', 'a rug can sit under a chair');
ok(G.placeFurniture('storage_chest', 5, 2, 0) === '' && G.storageCap() === 30, 'a Storage Chest adds 10 storage slots');
ok(G.questComplete('home'), 'Make It Home completes with two pieces placed');
const bagIdx = G.save.inventory.findIndex(s => s.id === 'potion');
G.giveItem('potion', 3, true);
const pIdx = G.save.inventory.findIndex(s => s.id === 'potion'); const pq = G.save.inventory[pIdx].qty;
ok(G.storeItem(pIdx) && G.save.storage.some(s => s.id === 'potion' && s.qty === pq) && G.invCount('potion') === 0, 'stored the potions with Pip');
ok(G.retrieveItem(0) && G.invCount('potion') === pq && G.save.storage.length === 0, 'took them back');
for (let i = 0; i < 30; i++) G.save.storage.push({ id: 'bone_chip', qty: 1 });
ok(G.removeFurniture(G.save.furniture.findIndex(f => f.id === 'storage_chest')) !== '', 'cannot pack away the chest while stored items would not fit');
G.save.storage = [];
ok(G.removeFurniture(G.save.furniture.findIndex(f => f.id === 'storage_chest')) === '' && G.invCount('storage_chest') === 1 && G.storageCap() === 20, 'packed the chest away');
const chair = G.save.furniture.findIndex(f => f.id === 'wooden_chair');
ok(G.rotateFurniture(chair) === '' && G.save.furniture[chair].rot === 1, 'rotated the chair');
P().x = 3.5 * 40 + 20; P().y = 3.5 * 40 + 20; G.keepOutOfRects(P());
ok(!(P().x > 124 && P().x < 156 && P().y > 124 && P().y < 156), 'placed furniture is solid');
const txt = G.exportSaveText(); const d = G.importSaveText(txt);
ok(d && d.furniture.length === 2 && Array.isArray(d.storage), 'furniture and storage survive save files');
G.enterZone('outpost', 262, 420); run(0.3);
G.TALK.talkOdette(npc('odette')); opt(/Report/).fn(); opt(/Collect/).fn();
ok(G.save.quests.home === 'done' && G.invCount('flowerpot') === 1 && G.invCount('herb_seeds') === 2, 'Odette rewards a flowerpot and herb seeds');

G.enterZone('hollow', 200, 1100); run(0.5);
const passive = S.mobs.filter(m => m.passive && !m.fam.nm), aggr = S.mobs.filter(m => !m.passive);
ok(passive.length >= 3 && passive.every(m => m.famKey === 'hare') && aggr.length >= 15, 'only critters are passive (' + passive.length + ') and the rest aggressive (' + aggr.length + ')');
const ph = passive[0];
P().x = ph.x + 20; P().y = ph.y; P().moving = true; run(1); P().moving = false;
ok(ph.state === 'idle', 'a hare ignores you walking beside it');
ph.enmity.set(P(), 10); ph.state = 'combat';
ok(ph.state === 'combat', 'but fights back when attacked');
const gw = aggr.find(m => m.famKey === 'goblin');
for (const m of S.mobs) if (m !== gw) m.alive = false;
gw.state = 'idle'; gw.face = 0; P().x = gw.x + 120; P().y = gw.y + 40; run(0.3);
ok(gw.state === 'combat', 'a goblin aggroes on sight');
let minD = 1e9; for (let i = 0; i < S.mobs.length; i++) for (let j = i + 1; j < S.mobs.length; j++) { const d = Math.hypot(S.mobs[i].home.x - S.mobs[j].home.x, S.mobs[i].home.y - S.mobs[j].home.y); if (d < minD) minD = d; }
ok(minD >= 150, 'spawn points are at least 150 px apart (' + Math.round(minD) + ')');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
