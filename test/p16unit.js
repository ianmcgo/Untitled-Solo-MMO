const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id);
const opt = re => S.dialog && S.dialog.all.find(o => re.test(o.label));
G.enterZone('marsh', 620, 2060); run(0.3); S.mobs = []; S.spawnAt = S.spawnAt.map(() => null);
ok(!!npc('chapel_door'), 'the Sealed Chapel Door stands at the Drowned Chapel');
G.talkTo(npc('chapel_door'));
ok(!opt(/Chapel Sigil and enter/), 'without a Chapel Sigil the door stays shut');
G.closeDialog && G.closeDialog();
G.giveItem('chapel_sigil', 1, true);
G.talkTo(npc('chapel_door')); opt(/enter/).fn();
ok(S.zoneId === 'depths' && S.bf && G.invCount('chapel_sigil') === 0, 'a sigil is used up and you enter the Chapel Depths');
run(4);
const boss = S.mobs.find(m => m.famKey === 'tide_priest');
ok(boss && boss.lv === 16 && boss.fam.boss, 'the Tidebound Priest appears');
boss.hp = Math.floor(boss.maxHp * 0.6); boss.enmity.set(P(), 10); boss.state = 'combat'; P().hp = P().maxHp = 99999; run(0.5);
ok(S.mobs.filter(m => m.famKey === 'drowned' && m.alive).length === 2, 'at 65% it calls two Drowned');
boss.hp = Math.floor(boss.maxHp * 0.45); run(6);
ok(boss.nextPulse > 0, 'below half it starts the Maelstrom');
const g0 = G.save.gil;
boss.hp = 1; G.applyDamage(P(), boss, 50, {}); run(0.5);
ok(S.bf && S.bf.won && G.save.gil >= g0 + 1500 && G.BATTLEFIELD.rewards.some(id => G.invCount(id) === 1) && G.save.stats.bfWins === 1, 'victory pays crystals, XP and one of the Priest\'s treasures');
run(40);
ok(!S.mobs.some(m => m.famKey === 'tide_priest' && m.alive), 'the Priest does not return after the win');
G.enterZone('marsh', 620, 2060); run(0.2);
ok(!S.bf, 'leaving ends the battlefield');
G.giveItem('chapel_sigil', 1, true); G.talkTo(npc('chapel_door')); opt(/enter/).fn(); run(0.2);
S.bf.until = S.time; run(0.2);
ok(S.zoneId === 'marsh' && !S.bf, 'running out of time sweeps you back to the marsh');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
