const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id);
const opt = re => S.dialog.all.find(o => re.test(o.label));
const inRect = (x, y, r, m) => x > r.x - m && x < r.x + r.w + m && y > r.y - m && y < r.y + r.h + m;

const z = G.ZONES.crypt;
const rects = G.zoneRects(z);
let bad = [];
z.spawns.forEach((sp, i) => { for (const r of rects) if (inRect(sp.x, sp.y, r, 30)) bad.push('spawn ' + i); });
for (const n of z.npcs) for (const r of rects) if (inRect(n.x, n.y, r, 20)) bad.push('npc ' + n.id);
for (const p of z.paths) for (let k = 0; k < p.pts.length - 1; k++) for (let t = 0; t <= 1; t += 0.02) { const x = p.pts[k][0] + (p.pts[k + 1][0] - p.pts[k][0]) * t, y = p.pts[k][1] + (p.pts[k + 1][1] - p.pts[k][1]) * t; if (x < 0 || x > z.w) continue; for (const r of rects) if (inRect(x, y, r, 10)) { bad.push('path ' + Math.round(x) + ',' + Math.round(y)); break; } }
ok(!bad.length, 'crypt layout clear of walls ' + bad.slice(0, 5).join('; '));
G.save.jobs.WAR.lv = 10; G.refreshPlayer(true);
G.enterZone('den', 1200, 1500); run(1);
ok(S.zone.exits.some(e => e.to === 'crypt'), 'the Den has an exit to the Crypt');
G.enterZone('crypt', 120, 700); run(1);
ok(S.zoneId === 'crypt' && S.mobs.length >= 5, 'crypt loads with its monsters (' + S.mobs.length + ')');
ok(S.npcs.filter(n => n.prop === 'brazier').length === 4 && S.npcs.some(n => n.prop === 'tablet'), 'four braziers and the inscription are present');
const gate = z.barriers.find(b => b.id === 'brazier_gate'), door = z.barriers.find(b => b.id === 'throne_door');
ok(!G.barrierOpen(gate) && !G.barrierOpen(door), 'gate and throne door start closed');
P().x = gate.x + gate.w / 2; P().y = 700; G.keepOutOfRects(P());
ok(!inRect(P().x, P().y, gate, -1), 'the closed gate is solid');
const order = G.brazierOrder();
ok(order.length === 4 && new Set(order).size === 4, 'brazier order is a permutation (' + order.join(',') + ')');
G.TALK.talkTablet(npc('crypt_tablet'));
ok(S.dialog.text.includes(G.BRAZIER_LINES ? '' : 'First'), 'the tablet reads the verse'); G.closeModal(); S.dialog = null;
const wrong = order[1];
const mobsBefore = S.mobs.length;
G.TALK.talkBrazier(npc('brazier_' + wrong)); opt(/Light/).fn();
ok(G.save.crypt.lit.length === 0 && S.mobs.length === mobsBefore + 2, 'wrong brazier snuffs the hall and raises two skeletons');
S.mobs = S.mobs.filter(m => m.spawnIdx != null); S.spawnAt = [];
for (const el of order) { G.TALK.talkBrazier(npc('brazier_' + el)); opt(/Light/).fn(); }
ok(G.save.crypt.solved && G.barrierOpen(gate) && G.closedBarrierRects(z).length === 1, 'lighting in order opens the gate');
ok(G.brazierLit('fire') && G.brazierLit('water'), 'braziers stay lit');
const sent = S.mobs.find(m => m.famKey === 'crypt_sentinel');
ok(sent && sent.fam.nm, 'the Crypt Sentinel stands in its room');
sent.enmity.set(P(), 10); G.onKO(sent, P());
ok(G.save.keyItems.includes('crypt_key') && G.invCount('crypt_key') === 0, 'the Sentinel drops the Crypt Key as a key item');
ok(G.barrierOpen(door), 'the throne door opens with the key');
ok(!G.giveKeyItem('crypt_key'), 'key items are not duplicated');
const king = S.mobs.find(m => m.famKey === 'hollow_king');
ok(king && king.lv === 12 && king.fam.boss, 'the Hollow King waits on his throne at level 12');
king.state = 'combat'; king.enmity.set(P(), 100); king.target = P();
const before = S.mobs.filter(m => m.alive).length;
king.hp = Math.floor(king.maxHp * 0.6); G.bossPhases(king, P());
ok(S.mobs.filter(m => m.alive).length === before + 2 && S.mobs.filter(m => m.famKey === 'royal_guard').length === 2, 'at 66% the King summons two Royal Guards');
G.bossPhases(king, P());
ok(S.mobs.filter(m => m.famKey === 'royal_guard').length === 2, 'guards are not summoned twice for one phase');
king.hp = Math.floor(king.maxHp * 0.3); G.bossPhases(king, P());
ok(S.mobs.filter(m => m.famKey === 'royal_guard').length === 4, 'at 33% two more guards');
const att0 = king.stats.att; king.hp = Math.floor(king.maxHp * 0.15); G.bossPhases(king, P());
ok(king.enraged && king.stats.att > att0 && king.delay < king.fam.delay, 'below 20% the King enrages');
const chest = npc('chest_king');
ok(G.chestState(chest) === 'sealed', 'the royal coffer is sealed while the King lives');
G.save.quests.hollowking = 'active'; G.save.qprog.hollowking = 0;
king.enmity.set(P(), 10); G.onKO(king, P());
ok(G.questComplete('hollowking') && G.save.timers['nm:hollow_king'] > Date.now() + 500000, 'defeating the King completes the quest and starts a 10-minute cooldown');
ok(G.chestState(chest) === 'closed', 'the royal coffer unseals');
const c1 = npc('chest_sent_a'); const inv0 = G.save.inventory.reduce((n, s) => n + s.qty, 0); const gil0 = G.save.gil;
G.openChest(c1);
ok(G.save.inventory.reduce((n, s) => n + s.qty, 0) > inv0 && G.save.gil > gil0 && G.chestState(c1) === 'empty', 'opening a chest gives loot and gil, then it is empty');
G.save.timers['chest:' + c1.id] = Date.now() - 1;
ok(G.chestState(c1) === 'closed', 'chests refill when their timer runs out');
const txt = G.exportSaveText(); const d = G.importSaveText(txt);
ok(d && d.crypt.solved && d.keyItems.includes('crypt_key'), 'crypt progress and key items survive save files');
G.enterZone('crypt', 120, 700); run(1);
ok(!S.mobs.some(m => m.famKey === 'hollow_king'), 'the King stays dead during his cooldown');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
