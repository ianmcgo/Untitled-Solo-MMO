const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const setLv = lv => { G.save.jobs[G.save.mainJob].lv = lv; G.refreshPlayer(true); };
G.enterZone('outpost'); run(1.5);
G.save.gil = 1e6; setLv(10);
const id = G.mercPool()[0];
G.hireMerc(id);
const fee = G.MERCS[id].fee;
ok(G.save.hired.includes(id) && Math.abs(G.mercContractLeft(id) - 3600) < 2, 'a hire comes with one hour of play time');
ok(G.mercWage(id) === Math.max(10, fee), 'a fresh hire\'s hourly wage equals the fee');
setLv(20);
ok(G.mercWage(id) > fee * 1.5, 'the wage rises with level (' + fee + ' at 10, ' + G.mercWage(id) + ' at 20)');
const w20 = G.mercWage(id);
const job = G.MERCS[id].job;
const piece = Object.keys(G.ITEMS).filter(k => G.ITEMS[k].kind === 'equip' && ['head', 'body', 'hands', 'legs', 'feet'].includes(G.ITEMS[k].slot) && G.ITEMS[k].jobs.includes(job) && G.ITEMS[k].lv <= 20).sort((a, b) => G.gearScore(b) - G.gearScore(a))[0];
G.save.mercGear[id] = { [G.ITEMS[piece].slot]: piece };
ok(G.mercWage(id) > w20, 'better gear raises the wage (' + w20 + ' to ' + G.mercWage(id) + ')');
G.tickWages(); const wSeen = G.save.mercWageSeen[id];
ok(wSeen === G.mercWage(id), 'the raise is noticed and announced');
G.save.mercGear[id] = {};
setLv(10);
ok(G.mercWage(id) === Math.max(10, fee), 'syncing down lowers the wage again');
G.save.playSec = (G.save.playSec || 0) + 3601;
ok(G.mercPayDue() === id, 'after an hour of play the contract is due');
S.modal = 'party';
ok(!G.mercPayReady(), 'no payment request while a menu is open');
S.modal = null; S.zoneCooldown = 1;
ok(!G.mercPayReady(), 'no payment request while zoning');
S.zoneCooldown = 0;
const m = G.buildMob('goblin', 10, P().x + 30, P().y, 0); S.mobs.push(m); m.state = 'combat'; m.enmity.set(P(), 100);
const inFight = !G.mercPayReady();
m.alive = false; S.mobs.splice(S.mobs.indexOf(m), 1);
ok(inFight, 'no payment request during a fight');
ok(G.mercPayReady(), 'out of combat, zoned in and no menus: ready to ask');
const g0 = G.save.gil, w = G.mercWage(id);
G.mercPay(id, true);
ok(G.save.gil === g0 - w && G.mercContractLeft(id) > 3500, 'paying takes the wage and adds an hour');
G.mercBag(id).push({ id: 'potion', qty: 2, sale: true });
G.addBond(id, 25);
const bond = G.save.bond[id];
G.save.playSec += 3601;
G.mercPay(id, false);
ok(!G.save.hired.includes(id) && G.save.oldFriends[id] && !S.party.some(p => p.mercId === id), 'refusing sends them to Old Friends');
G.mercPool(G.mercPool.length ? undefined : undefined);
ok(G.MERCS[id] && G.save.mercDefs[id], 'their details are kept');
G.save.gil = 50;
ok(G.rehireFriend(id) !== '' && !G.save.hired.includes(id), 'the bribe must be paid');
setLv(15);
ok(G.mercBribe(id) === G.save.oldFriends[id].fee + 100 * 15, 'the bribe is the full hiring fee plus 100 per level');
G.save.gil = 1e6; const b = G.mercBribe(id), g1 = G.save.gil;
G.rehireFriend(id);
const back = S.party.find(p => p.mercId === id);
ok(G.save.hired.includes(id) && !G.save.oldFriends[id] && G.save.gil === g1 - b, 'paying the bribe brings them back');
ok(back && back.lv === 15 && G.save.bond[id] === bond && G.mercBag(id).some(x => x.id === 'potion'), 'they rejoin at your level with bond and bag kept');
G.save.gil = 0; G.save.playSec += 3601;
G.mercPay(id, true);
ok(G.save.oldFriends[id] && !G.save.hired.includes(id), 'if you cannot pay they leave too');
const sv = JSON.parse(JSON.stringify(G.save)); sv.mercPaid = { x: 1 }; sv.hired = [];
G.save = G.normalizeSave(sv);
G.tickWages();
ok(!Object.keys(G.save.mercPaid || {}).length, 'old real-time wage timers are dropped');
console.log(fails ? fails + ' FAILED' : 'ALL PASS'); process.exit(fails ? 1 : 0);
