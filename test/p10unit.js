const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id);

G.enterZone('outpost'); run(0.3);
ok(npc('garrick') && npc('trade_board'), 'Garrick the smith and the Trade Board are in the Outpost');
G.giveItem('bronze_sword', 1, true);
ok(G.canAugment('bronze_sword', false) !== '', 'augmenting needs materials and crystals');
G.giveItem('iron_ore', 3, true); G.giveItem('fire_crystal', 3, true); G.save.gil = 5000;
const att0 = P().stats.att;
ok(G.augmentItem(P().gear.main || 'bronze_sword', false) === '' && G.save.augments[P().gear.main || 'bronze_sword'].length === 1, 'Garrick adds an augment');
G.augmentItem(P().gear.main, false);
ok(G.save.augments[P().gear.main].length === 2 && G.canAugment(P().gear.main, false) !== '', 'two augments is the limit');
const before = JSON.stringify(G.save.augments[P().gear.main]);
G.augmentItem(P().gear.main, true);
ok(G.save.augments[P().gear.main].length === 2, 'reforging rerolls both augments');
const aug = G.save.augments[P().gear.main];
ok(aug.every(([k]) => P().stats[k] !== undefined || ['hp', 'mp'].includes(k)), 'augments feed into your stats');
const reqs = G.boardToday();
ok(reqs.length === 3 && new Set(reqs.map(r => r.id)).size === 3, 'the board shows three different requests today');
const r = reqs[0]; for (const it in r.items) G.removeItem(it, G.invCount(it));
ok(G.fillTrade(r.id) !== '', 'a request needs its items');
for (const it in r.items) G.giveItem(it, r.items[it], true);
const g0 = G.save.gil;
ok(G.fillTrade(r.id) === '' && G.save.gil === g0 + r.gil && G.save.board.done.includes(r.id), 'filling a request pays crystals');
ok(G.fillTrade(r.id) !== '', 'each request can only be filled once a day');
G.hireMerc('kael'); G.hireMerc('mira');
G.save.jobs.WAR.lv = 20; G.refreshPlayer(true);
G.addToPool('neckchopper');
ok(S.pool.length === 1, 'equipment drops go to the treasure pool when you have companions');
const saved = Math.random; Math.random = () => 0.999;
run(2);
const e = S.pool[0];
ok(e && e.lots.kael > 0 && e.lots.mira === 0, 'Kael lots on an axe upgrade, Mira passes');
Math.random = () => 0.0; G.lotPool(e.seq, false); Math.random = saved;
ok(!S.pool.length && G.save.mercGear.kael && G.save.mercGear.kael.main === 'neckchopper', 'the high lot wins and Kael equips it');
const fillBag = id => { const b = G.mercBag(id); b.length = 0; for (let i = 0; i < 30; i++) b.push({ id: 'bronze_dagger', qty: 1, sale: true }); };
fillBag('kael'); fillBag('mira');
G.addToPool('bronze_dagger'); run(2);
G.lotPool(S.pool[0].seq, false);
ok(!S.pool.length && G.invCount('bronze_dagger') === 1, 'with no rival lots, your lot wins the item');
G.addToPool('bronze_dagger'); run(2); G.lotPool(S.pool[0].seq, true);
ok(!S.pool.length && G.invCount('bronze_dagger') === 1, 'if everyone passes, the item is lost');
G.mercBag('kael').length = 0; G.mercBag('mira').length = 0;
S.party.length > 1 && G.lootGive('potion', []);
ok(S.pool.length === 1 && S.pool[0].id === 'potion', 'non-equipment drops go to the pool too');
Math.random = () => 0.999; run(2);
ok(S.pool[0].lots.kael > 0 && S.pool[0].lots.mira > 0, 'companions lot on any item they can carry');
Math.random = () => 0.0; G.lotPool(S.pool[0].seq, true); Math.random = saved;
ok(!S.pool.length && G.mercBagCount('kael') + G.mercBagCount('mira') === 1, 'a companion who wins keeps a potion in their bag');
G.addToPool('neckchopper'); Math.random = () => 0.999; run(2); Math.random = saved;
ok(S.pool[0].lots.mira === 0, 'a companion passes on gear they cannot wear');
G.lotPool(S.pool[0].seq, true);
fillBag('mira');
ok(!G.mercWants(S.party.find(p => p.mercId === 'mira'), 'potion'), 'a companion with a full bag passes on everything');
const bag = G.mercBag('kael'); bag.length = 0; for (let i = 0; i < 15; i++) bag.push({ id: 'bronze_dagger', qty: 1, sale: true });
S.zone = { theme: 'town', city: 'Testville' }; G.mercTownSell();
ok(G.mercBag('kael').length === 0 && G.mercBag('mira').length === 0 || G.mercBag('kael').length === 0, 'half-full bags are sold off in a town');
const bag2 = G.mercBag('kael'); for (let i = 0; i < 14; i++) bag2.push({ id: 'bronze_dagger', qty: 1, sale: true });
G.mercTownSell();
ok(G.mercBag('kael').length === 14, 'bags under half full are kept in town');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
