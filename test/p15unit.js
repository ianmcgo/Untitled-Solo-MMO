const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id);
const opt = re => S.dialog && S.dialog.all.find(o => re.test(o.label));
G.enterZone('outpost'); run(0.2);
G.save.jobs.WAR.lv = 6; G.refreshPlayer(true);
G.talkTo(npc('tobin'));
ok(!!opt(/Steady Aim/) && !!opt(/The Calling/), 'Tobin offers the Ranger and Summoner quests');
opt(/Steady Aim/).fn(); opt(/^Accept$/).fn();
G.giveItem('bat_wing', 3, true); G.giveItem('ash_lumber', 2, true);
G.talkTo(npc('tobin')); opt(/Steady Aim/).fn(); opt(/Collect/).fn();
ok(G.save.jobsUnlocked.RNG && G.invCount('shortbow') === 1, 'Steady Aim unlocks Ranger and gives a bow');
G.setJob('RNG', null); G.equip('shortbow');
ok(P().stats.wtype === 'archery' && G.reach(P()) > 200, 'a Ranger shoots from long range');
G.enterZone('hollow', 300, 1100); run(0.2); S.mobs = []; S.spawnAt = S.spawnAt.map(() => null);
const m = G.buildMob('goblin', 2, P().x + 180, P().y, 0); S.mobs.push(m); m.face = 0;
P().target = m; G.toggleEngage(); const hp0 = m.hp; run(9);
ok(m.hp < hp0 && Math.hypot(P().x - 300, P().y - 1100) < 70, 'the Ranger hits from where they stand');
G.save.jobs.RNG.lv = 10; G.refreshPlayer(true);
m.hp = m.maxHp; P().target = m; G.playerAct({ kind: 'ja', id: 'shadowbind' });
const mx = m.x; run(2);
ok(m.buffs.bind && Math.abs(m.x - mx) < 2, 'Shadowbind pins a monster in place');
G.save.jobsUnlocked.SMN = true; G.save.jobs.SMN.lv = 10; G.setJob('SMN', null); P().mp = P().maxMp;
G.enterZone('hollow', 300, 1100); run(0.2); S.mobs = []; S.spawnAt = S.spawnAt.map(() => null);
G.playerAct({ kind: 'ma', id: 'fire_spirit' }); run(4);
ok(S.pet && S.party.includes(S.pet) && S.pet.name === 'Fire Spirit', 'casting Fire Spirit summons a sprite into the party');
const mp1 = P().mp; run(4);
ok(P().mp < mp1, 'the sprite slowly drains MP');
const m2 = G.buildMob('goblin', 6, P().x + 60, P().y, 0); S.mobs.push(m2); P().target = m2;
const h2 = m2.hp; G.playerAct({ kind: 'ja', id: 'blood_pact' });
ok(m2.hp < h2, 'Blood Pact deals damage through the sprite');
G.playerAct({ kind: 'ja', id: 'release' });
ok(!S.pet && !S.party.some(p => p.pet), 'Release sends the sprite home');
G.playerAct({ kind: 'ma', id: 'fire_spirit' }); run(4); P().mp = 0; run(4);
ok(!S.pet, 'the sprite fades when MP runs out');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
