const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id);
G.save.story.done = true;
G.enterZone('outpost'); run(0.2);
ok(!!npc('auction_outpost'), 'The auction counter stands the auction house in the Outpost');
G.enterZone('harbor', 600, 420); run(0.2);
ok(!!npc('auction_harbor'), 'A counter stands the one in Saltreach');
ok(G.ahTradable('iron_ore') && G.ahTradable('spatha') && !G.ahTradable('fasting_ring') && !G.ahTradable('multiple_ring') && !G.ahTradable('ashen_shard'), 'rare, Ex and key items stay off the market');
const hist = G.priceHistory('iron_ore', 12);
ok(new Set(hist).size > 3, 'prices move over time: ' + hist.join(','));
const base = G.ITEMS.iron_ore.price * G.CONFIG.shopMul * 1.5;
ok(hist.every(p => p > base * 0.5 && p < base * 1.8), 'and stay near the usual value (' + base + ')');
ok(G.priceHistory('spatha', 12).every(v => v > G.ITEMS.spatha.price * G.CONFIG.shopMul * 0.9 && v < G.ITEMS.spatha.price * G.CONFIG.shopMul * 2.5), 'auction prices sit around 1.5x the shop price');
const n1 = G.marketNews(G.marketDay()); ok(n1.up !== n1.down && n1.text.length === 2, 'each day brings market news');
G.save.gil = 100000;
const st = G.ahStock('iron_ore'), p0 = G.marketPrice('iron_ore');
if (st > 0) {
  ok(G.ahBuy('iron_ore', 1) === '' && G.invCount('iron_ore') >= 1 && G.ahStock('iron_ore') === st - 1, 'buying takes one from today\'s stock');
  ok(G.marketPrice('iron_ore') >= p0, 'buying pushes the price up');
} else ok(G.ahBuy('iron_ore', 1) !== '', 'no stock, no sale');
G.giveItem('spatha', 1, true);
const g0 = G.save.gil, mp = G.marketPrice('spatha');
ok(G.ahList('spatha', 1, mp) === '' && G.save.gil === g0 - Math.max(1, Math.ceil(mp * 0.03)) && G.invCount('spatha') === 0, 'listing takes the item and a 3% fee');
ok(G.ahList('fasting_ring', 1, 10) !== '', 'rare items cannot be listed');
const l = G.save.market.listings[0];
ok(G.saleChance({ id: 'spatha', qty: 1, price: mp * 0.5 }) > G.saleChance({ id: 'spatha', qty: 1, price: mp * 2 }), 'cheaper lots sell faster');
l.price = Math.round(mp * 0.6); l.next = Date.now() - 30 * 60000;
const g1 = G.save.gil; G.tickAuction();
ok(G.save.market.listings.length === 0 && G.save.gil >= g1 + l.price && G.save.stats.ahSold === 1, 'a cheap lot sells while you\'re away and pays out');
G.giveItem('iron_ore', 3, true);
G.ahList('iron_ore', 3, 999999);
const l2 = G.save.market.listings[0]; l2.next = Date.now() - 10; l2.exp = Date.now() - 1; G.tickAuction();
ok(G.save.market.listings.length === 0 && G.save.market.box.some(b => b.id === 'iron_ore' && b.qty === 3), 'an unsold lot comes back to the delivery box');
const before = G.invCount('iron_ore'); G.ahCollect();
ok(G.invCount('iron_ore') === before + 3 && !G.save.market.box.length, 'collecting the box returns the items');
G.giveItem('potion', 1, true); G.ahList('potion', 1, 50); G.ahCancel(0);
ok(G.save.market.box.some(b => b.id === 'potion'), 'withdrawing a lot sends it to the box');
for (let i = 0; i < 8; i++) { G.giveItem('bait', 1, true); G.ahList('bait', 1, 99999); }
ok(G.save.market.listings.length === G.AH_CFG.maxListings, 'at most ' + G.AH_CFG.maxListings + ' lots at once');
const raw = JSON.parse(G.exportSaveText()); const body = raw.data || raw; delete body.market;
const n = G.importSaveText(JSON.stringify(raw));
ok(n && n.market && Array.isArray(n.market.listings) && n.market.listings.length === 0, 'old saves get an empty market record');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
