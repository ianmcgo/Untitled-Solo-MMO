const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };

G.save.gil = 5000; G.enterZone('outpost'); run(0.2);
G.hireMerc('kael');
ok(G.save.hired.includes('kael') && G.save.mercPaid.kael > Date.now(), 'hiring sets the first paid day');
const g0 = G.save.gil, w = G.mercWage('kael');
G.save.mercPaid.kael = Date.now() - 1; G.tickWages();
ok(G.save.gil === g0 - w && G.save.mercPaid.kael > Date.now(), 'a day later the wage is paid automatically (' + w + ')');
G.save.gil = 0; G.save.mercPaid.kael = Date.now() - 1; G.tickWages();
ok(!G.save.hired.includes('kael') && S.party.length === 1, 'an unpaid companion goes back to the hall');
G.save.gil = 5000; G.hireMerc('kael');
const k = () => S.party.find(p => p.mercId === 'kael');
const hp0 = k().maxHp;
G.addBond('kael', G.COMPANION_CFG.bondSteps[2]);
ok(G.bondLevel('kael') === 2 && k().maxHp > hp0, 'bond level raises companion stats');
G.save.jobs.WAR.lv = 7; G.refreshPlayer(true);
const up = Object.keys(G.ITEMS).find(id => G.ITEMS[id].kind === 'equip' && ['head', 'body', 'hands', 'legs', 'feet'].includes(G.ITEMS[id].slot) && G.ITEMS[id].lv <= 7 && G.ITEMS[id].jobs.includes('WAR') && G.mercUpgrade('kael', id));
const upSlot = G.ITEMS[up].slot;
G.giveItem(up, 1, true);
ok(G.giveMercGear('kael', up) === '' && k().gear[upSlot] === up && G.invCount(up) === 0, 'giving a better piece moves it from your bag to the companion');
ok(G.giveMercGear('kael', 'maple_wand') !== '', 'a companion refuses gear their job cannot use');
G.takeMercGear('kael', upSlot);
ok(G.invCount(up) === 1 && !G.save.mercGear.kael[upSlot], 'taking gear back returns it');
G.setStance('follow');
G.enterZone('hollow', 300, 1100); run(0.5);
const m = G.buildMob('goblin', 1, P().x + 60, P().y, 0); m.hp = m.maxHp = 9999; S.mobs.push(m);
m.enmity.set(P(), 10); m.state = 'combat'; P().target = m; G.toggleEngage(); run(2);
ok(!k().engaged, 'on follow, companions do not attack');
G.setStance('assist'); run(2);
ok(k().engaged && k().attackTarget === m, 'on assist, companions join the fight');
const bx = k().x, by = k().y; G.setStance('hold'); run(1.5);
ok(Math.hypot(k().x - bx, k().y - by) < 40, 'on hold, companions stay put');
G.setStance('assist');
m.hp = 1; run(4);
ok(!m.alive && G.save.stats.kills >= 1 && G.save.bestiary.goblin && G.save.bestiary.goblin.kills >= 1, 'a kill counts in stats and the bestiary');
G.checkAchievements();
ok(G.save.ach.first_blood && G.save.ach.companion, 'achievements unlock from stats');
const hare = G.buildMob('hare', 1, P().x + 100, P().y + 100, 0); S.mobs.push(hare); run(1);
ok(!G.save.bestiary.hare, 'meeting a creature does not record it; only a kill does');
G.ZONES.hollow.colliders = [{ x: P().x + 20, y: P().y, r: 5 }];
P().x = G.ZONES.hollow.colliders[0].x - 2; P().y = G.ZONES.hollow.colliders[0].y; G.keepOutOfColliders(P());
ok(Math.hypot(P().x - G.ZONES.hollow.colliders[0].x, 0) >= 5, 'trees and poles push you out');
G.ZONES.hollow.colliders = [];
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
