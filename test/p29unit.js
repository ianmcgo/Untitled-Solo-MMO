const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player; G.save.story.done = true;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
G.save.gil = 99999;
const pool = G.mercPool();
ok(pool.length === 5 && pool.every(id => G.MERCS[id] && G.MERCS[id].gen), 'the guild offers 5 generated hires');
ok(new Set(pool.map(id => G.MERCS[id].name)).size >= 3 && pool.every(id => G.MERCS[id].fee > 0 && G.JOBS[G.MERCS[id].job]), 'hires have names, jobs and fees');
ok(G.mercPool().join() === pool.join(), 'the same day gives the same hires');
const id = pool[0];
G.hireMerc(id);
const m = S.party.find(p => p.mercId === id);
ok(m && m.lv === P().lv, 'a hire joins at your level');
const pool2 = G.mercPool(G.save.mercDay.day + 1);
ok(pool2.join() !== pool.join() && G.save.hired.includes(id) && G.MERCS[id], 'the stock changes daily but your hire stays');
m.hp = 1; G.onKO(m, null); run(5);
ok(G.save.hired.includes(id) && !m.alive, 'a KO\'d hire stays down and can still be raised');
G.revive(m, 0.25, 'Test');
ok(m.alive && m.hp === Math.round(m.maxHp * 0.25) && m.buffs.weakened, 'reviving brings them back weakened');
m.hp = 1; G.onKO(m, null); m.koUntil = Date.now() - 1; run(5);
ok(!G.save.hired.includes(id) && G.save.mercFallen[id] && !S.party.some(p => p.mercId === id), 'a fallen hire leaves for good');
G.hireMerc(id);
ok(!G.save.hired.includes(id), 'a fallen hire cannot be hired again');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
