const { chromium } = require('/opt/npm-tools/node_modules/playwright');
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 800, height: 600 }, hasTouch: true });
  const errs = [];
  page.on('pageerror', e => errs.push('pageerror: ' + e.message));
  page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await page.addInitScript(() => localStorage.setItem('ashenreach_settings_v1', JSON.stringify({ quality: 'low' })));
  await page.goto('file:///home/claude/build/dist/index.html');
  await page.waitForTimeout(3000);
  const p0 = await page.evaluate(() => [player.x, player.y]);
  await page.keyboard.down('w'); await page.waitForTimeout(2500); await page.keyboard.up('w');
  const p1 = await page.evaluate(() => [player.x, player.y, VIEW.yaw]);
  await page.evaluate(() => enterZone('hollow', 300, 600));
  await page.waitForTimeout(3000);
  await page.keyboard.press('Tab'); await page.waitForTimeout(500);
  const t = await page.evaluate(() => player.target && player.target.name);
  const box = await page.locator('#game').boundingBox();
  await page.mouse.move(box.x + 400, box.y + 300); await page.mouse.down(); await page.mouse.move(box.x + 520, box.y + 320, { steps: 5 }); await page.mouse.up();
  const yaw2 = await page.evaluate(() => VIEW.yaw);
  await page.mouse.click(box.x + 400, box.y + 450);
  await page.waitForTimeout(800);
  const mt = await page.evaluate(() => S.moveTarget);
  await page.touchscreen.tap(box.x + 600, box.y + 200);
  await page.evaluate(() => { const m = nearestMob(); player.target = m; toggleEngage(true); });
  await page.waitForTimeout(4000);
  const eng = await page.evaluate(() => [player.engaged, S.chase, Math.round(dist(player, player.attackTarget || player))]);
  await page.evaluate(() => openModal('settings'));
  await page.waitForTimeout(500);
  const settingsHtml = await page.evaluate(() => $('mBody').innerHTML.includes('Graphics'));
  console.log(JSON.stringify({ moved: [p0, p1], target: t, yawChanged: Math.abs(yaw2 - p1[2]) > 0.1, moveTarget: !!mt, engaged: eng, settingsHtml }));
  console.log(errs.length ? errs.join('\n') : 'no errors');
  await browser.close();
})();
