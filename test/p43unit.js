const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id) || G.meet(id);
const opt = re => S.dialog && S.dialog.all.find(o => re.test(o.label));
G.enterZone('outpost'); run(0.2);
const c0 = G.conquestState();
ok(c0.held.vale === 'ash' && c0.held.mire === 'beast' && !c0.nation, 'regions start with their own holders and you start unpledged');
G.save.quests.pouches = 'done';
G.talkTo(npc('rhea'));
const pl = opt(/Pledge to the Ashenreach/);
ok(!!pl, 'Captain Rhea asks you to pledge to the League');
if (pl) pl.fn();
ok(G.conquestState().nation === 'ash', 'you fight for the Ashenreach League');
G.enterZone('marsh', 1400, 300); run(0.3);
const m = G.buildMob('bog_toad', 14, P().x + 40, P().y, 0); S.mobs.push(m);
for (let i = 0; i < 40; i++) G.killRewards(m);
ok((G.conquestState().pts.mire || {}).ash > 100, 'victories in the Mire count for the League');
S.timeShift += 86400000; G.conquestState();
ok(G.conquestState().held.mire === 'ash', 'after the daily tally the League holds the Mire');
const p0 = G.ITEMS.potion.price;
ok(G.heldCount('ash') >= 3 && G.buyPrice('potion') < p0 * G.CONFIG.shopMul, 'holding three regions makes League shops cheaper');
G.runCommand('/conquest');
ok(H.alllog.slice(-3).join(' ').includes('held by'), '/conquest reports who holds each region');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
