const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
run(0.3);
const gr = G.RECIPES.filter(r => r.id.startsWith('g_'));
ok(gr.length > 100, 'generated recipes make the common +1 gear (' + gr.length + ')');
ok(G.RECIPES.every(r => G.ITEMS[r.out] && (!r.hq || G.ITEMS[r.hq]) && Object.keys(r.mats).every(m => G.ITEMS[m])), 'every recipe uses real items');
ok(gr.every(r => G.ITEMS[r.hq].name === G.ITEMS[r.out].name + ' +1' && r.lv === Math.min(20, G.ITEMS[r.out].lv)), 'a recipe makes the item and its +1 at the item level');
ok(new Set(G.RECIPES.map(r => r.out)).size === G.RECIPES.length, 'no item has two recipes');
const kinds = new Set(gr.map(r => r.craft));
ok(['smithing', 'woodworking', 'clothcraft', 'alchemy'].every(k => kinds.has(k)), 'gear recipes cover Smithing, Woodworking, Clothcraft and Alchemy');
ok(G.GEAR_DATA.lgn_staff.src === 'drop' && G.GEAR_DATA.ryl_ftm_tunic.src === 'drop' && !G.SHOP.includes('lgn_staff'), 'Legionnaire and Royal pieces are drops, not shop stock');
const c = G.mobCurve(20), c1 = G.mobCurve(1);
ok(c.hp < 0.8 && c.att < 0.9 && c1.hp === 1, 'the monster curve weakens high-level monsters and leaves level 1 alone');
G.save.gil = 0; const m = G.buildMob('hill_lizard', P().lv, P().x + 20, P().y, null); m.alive = false; G.dropLoot(m, []);
ok(G.save.gil > 0, 'a non-beastman monster that gives XP drops crystals');
const ag = G.autoGear('RNG', 12, 'dd');
ok(ag.ranged && G.ITEMS[ag.ranged].wtype === 'archery' && ag.ammo && ag.main, 'companion rangers get a bow, ammo and a melee weapon');
G.save.jobsUnlocked.RNG = true; G.save.jobs.RNG.lv = 12; G.setJob('RNG', null);
for (const id of ['self_bow', 'bone_arrow']) G.giveItem(id, 1, true);
G.equip('self_bow'); G.equip('bone_arrow'); G.refreshPlayer(true);
ok(P().stats.wtype === 'archery' && P().stats.dmg === G.ITEMS.self_bow.dmg + Math.round(G.ITEMS.bone_arrow.dmg * G.CONFIG.ammoDmgMul), 'a bow in Range shoots and ammo adds half its damage');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
