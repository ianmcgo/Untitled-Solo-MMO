const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id);
const opt = re => S.dialog && S.dialog.all.find(o => re.test(o.label));
G.enterZone('outpost'); run(0.2);
G.save.jobs[G.save.mainJob].lv = 12; G.refreshPlayer(true);
G.talkTo(npc('maera'));
ok(!!opt(/Across the Wilds/) && !opt(/Fire and Water/), 'Maera offers the level 12 expedition only');
opt(/Across the Wilds/).fn(); opt(/Set out/).fn();
ok(G.save.exped && G.save.exped.id === 'wilds', 'the expedition begins');
G.enterZone('ironvale'); run(1.2);
ok(G.save.exped.step === 1, 'reaching Ironvale ticks off the first leg');
G.talkTo(npc('brisa')); run(0.2);
ok(G.save.exped.step === 2, 'talking to Brisa ticks off the second leg');
const lm = G.ZONES.sunscar.landmarks.find(l => l.id === 'ribs');
G.enterZone('sunscar', lm.x + 20, lm.y); run(1.2);
ok(G.save.exped.step === 3, 'standing at Titan\'s Ribs ticks off the third leg');
G.enterZone('outpost'); run(0.3);
const g0 = G.save.gil;
G.talkTo(npc('maera')); opt(/Report: Across the Wilds/).fn();
ok(!G.save.exped && G.save.expDone.wilds && G.save.gil === g0 + 2000 && G.invCount('holly_clogs') === 1, 'reporting back pays out and gives the Trailblazer Boots');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
