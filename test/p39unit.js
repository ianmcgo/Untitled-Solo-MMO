const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id);
const opt = re => S.dialog && S.dialog.all.find(o => re.test(o.label));
G.enterZone('harbor', 560, 700); run(0.3);
ok(!!npc('ferry_harbor'), 'a ferryman waits on the Saltreach docks');
G.save.gil = 50; G.talkTo(npc('ferry_harbor')); opt(/Sail to Gull Isle/).fn(); run(0.2);
ok(S.zoneId === 'harbor' && G.save.gil === 50, 'the ferry needs the fare');
G.save.gil = 500; G.talkTo(npc('ferry_harbor')); opt(/Sail to Gull Isle/).fn(); run(2);
ok(S.zoneId === 'harbor' && G.save.gil === 400, 'boarding takes the fare and the trip takes a while');
run(5);
ok(S.zoneId === 'gullisle', 'the ferry lands on Gull Isle');
ok(!!npc('wend') && !!npc('ferry_isle'), 'Old Wend and the return ferry are on the island');
ok(S.mobs.length > 0 && S.mobs.every(m => m.lv >= 12 && m.lv <= 17), 'island monsters are level 12 to 16');
G.save.jobs[G.save.mainJob].lv = 12; G.refreshPlayer(true);
G.talkTo(npc('wend'));
ok(!!opt(/Supper for Wend/), 'Old Wend has a favour to ask');
G.talkTo(npc('ferry_isle')); opt(/Sail to Saltreach/).fn(); run(7);
ok(S.zoneId === 'harbor', 'the ferry brings you back to Saltreach');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
