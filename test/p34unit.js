const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
G.save.spells = Object.keys(G.SPELLS);
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id);
const opt = re => S.dialog && S.dialog.all.find(o => re.test(o.label));
G.enterZone('outpost'); run(0.2);
G.save.jobs.WAR.lv = 18; G.refreshPlayer(true);
G.talkTo(npc('tobin'));
ok(!!opt(/Shape of the Land/) && !!opt(/Carved in Steel/), 'Tobin offers the Geomancer and Rune Fencer quests at 18');
opt(/Carved in Steel/).fn(); opt(/^Accept$/).fn();
G.giveItem('orc_tooth', 2, true); G.giveItem('iron_ingot', 2, true);
G.talkTo(npc('tobin')); opt(/Carved in Steel/).fn(); opt(/Collect/).fn();
ok(G.save.jobsUnlocked.RUN && G.invCount('claymore') === 1, 'Carved in Steel unlocks Rune Fencer and gives a greatsword');
G.setJob('RUN', null); G.equip('claymore'); G.save.jobs.RUN.lv = 15; G.refreshPlayer(true);
ok(P().stats.wtype === 'gsword', 'Rune Fencers swing great swords');
G.enterZone('hollow', 300, 1100); run(0.2); S.mobs = []; S.spawnAt = S.spawnAt.map(() => null);
const m = G.buildMob('goblin', 12, P().x + 40, P().y, 0); m.hp = m.maxHp = 99999; S.mobs.push(m);
P().target = m;
for (const r of ['kindle_rune', 'rime_rune', 'gale_rune', 'stone_rune']) { P().recasts['ja:' + r] = 0; G.playerAct({ kind: 'ja', id: r }); run(0.1); }
ok(P().buffs.runes && P().buffs.runes.list.length === 3, 'runes stack to three');
const hp0 = P().hp; G.applyDamage(m, P(), 100); ok(hp0 - P().hp === 85, 'three runes cut damage taken by 15%');
const mh = m.hp; G.playerAct({ kind: 'ja', id: 'lunge' }); run(0.1);
ok(m.hp < mh && !P().buffs.runes, 'Lunge spends the runes for damage');
G.save.jobsUnlocked.GEO = true; G.save.jobs.GEO.lv = 15; G.giveItem('ash_club', 1, true); G.setJob('GEO', null); G.equip('ash_club'); G.refreshPlayer(true); P().mp = P().maxMp;
P().target = P(); G.playerAct({ kind: 'ma', id: 'indi_fury' }); run(3.5);
ok(P().indi && P().buffs.geo_fury, 'Aura of Fury surrounds you and buffs you');
P().target = m; P().mp = P().maxMp; G.playerAct({ kind: 'ma', id: 'geo_frailty' }); run(3.5);
ok(P().luopan && m.buffs.geo_frail, 'Ward of Frailty plants a luopan that weakens nearby monsters');
const mp1 = P().mp; G.playerAct({ kind: 'ja', id: 'full_circle' }); run(0.1);
ok(!P().luopan && P().mp > mp1, 'Full Circle dismisses the luopan and refunds MP');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
