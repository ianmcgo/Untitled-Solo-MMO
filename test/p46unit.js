const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id);
const setHour = h => { const v = G.vana(); let d = h - v.hour; if (d < 0) d += 24; S.timeShift += d * 3600000 / 25; };
const findWx = (z, w) => { for (let k = 0; k < 400; k++) { S.timeShift = k * 3 * 3600000 / 25; if (G.weatherNow(z) === w) return true; } return false; };
G.enterZone('outpost'); setHour(12); run(0.5);
ok(npc('luna') && npc('luna').away, 'the Moonlit Peddler is nowhere to be seen by day');
setHour(22); run(0.5);
ok(!npc('luna').away, 'she sets up shop at night');
ok(G.SHOPS.luna.includes('shield_earring'), 'she sells things you cannot buy by day');
findWx('sunscar', 'clear');
const door = G.ZONES.sunscar.exits.find(e => e.to === 'mirage');
G.enterZone('sunscar', door.x + 20, door.y - 60); run(0.5);
ok(npc('mirage_shimmer').away, 'no mirage in clear weather');
P().x = door.x + 20; P().y = door.y + 20; run(1.5);
ok(S.zoneId === 'sunscar', 'the mirage door does nothing without a sandstorm');
findWx('sunscar', 'sandstorm'); G.enterZone('sunscar', door.x + 20, door.y - 60); run(0.5);
ok(!npc('mirage_shimmer').away, 'the air shimmers in a sandstorm');
ok(G.ZONES.mirage && G.NM_FAMILIES.sandglass_wisp && G.NM_FAMILIES.gloamhorn, 'the Mirage holds the Sandglass Wisp, and Gloamhorn grazes the Highlands by night');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
