const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
G.save.spells = Object.keys(G.SPELLS);
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id);
const opt = re => S.dialog && S.dialog.all.find(o => re.test(o.label));
G.enterZone('outpost'); run(0.2);
for (const j in G.JOBS) G.save.jobsUnlocked[j] = true;
G.save.jobs.WAR.lv = 16; G.refreshPlayer(true);
G.talkTo(npc('tobin'));
ok(!!opt(/Strings and Springs/) && !!opt(/First Step/) && !!opt(/Ink and Insight/), 'Tobin offers the Puppetmaster, Dancer and Scholar quests at 16');
opt(/Strings and Springs/).fn(); opt(/^Accept$/).fn();
G.giveItem('ash_lumber', 3, true); G.giveItem('bronze_ingot', 2, true);
G.talkTo(npc('tobin')); opt(/Strings and Springs/).fn(); opt(/Collect/).fn();
ok(G.save.jobsUnlocked.PUP, 'Strings and Springs unlocks Puppetmaster');
G.setJob('PUP', null); G.equip('cesti'); G.save.jobs.PUP.lv = 15; G.refreshPlayer(true);
G.enterZone('hollow', 300, 1100); run(0.2); S.mobs = []; S.spawnAt = S.spawnAt.map(() => null);
G.playerAct({ kind: 'ja', id: 'activate' }); run(0.3);
ok(S.pet && S.pet.automaton, 'Activate brings out the automaton');
S.pet.hp = 1; G.playerAct({ kind: 'ja', id: 'repair' }); run(0.1);
ok(S.pet.hp > S.pet.maxHp * 0.4, 'Repair patches it up');
G.save.jobsUnlocked.DNC = true; G.save.jobs.DNC.lv = 15; G.giveItem('bronze_dagger', 1, true); G.setJob('DNC', null); G.equip('bronze_dagger'); G.refreshPlayer(true); run(0.2);
ok(!S.pet, 'the automaton winds down on job change');
const m = G.buildMob('goblin', 10, P().x + 40, P().y, 0); m.hp = m.maxHp = 99999; S.mobs.push(m);
P().target = m; P().tp = 0;
G.playerAct({ kind: 'ja', id: 'quick_step' }); run(0.1);
ok(!m.buffs.stepped, 'Quick Step needs TP');
P().tp = 1000; P().recasts['ja:quick_step'] = 0; G.playerAct({ kind: 'ja', id: 'quick_step' }); run(0.1);
P().recasts['ja:quick_step'] = 0; G.playerAct({ kind: 'ja', id: 'quick_step' }); run(0.1);
ok(m.buffs.stepped && m.buffs.stepped.n === 2 && P().tp === 800, 'Quick Step stacks and spends TP');
const h0 = m.hp; G.playerAct({ kind: 'ja', id: 'rising_flourish' }); run(0.1);
ok(m.hp < h0 && !m.buffs.stepped, 'Rising Flourish spends the steps for damage');
P().hp = Math.floor(P().maxHp / 3); P().tp = 400; const ph = P().hp;
G.playerAct({ kind: 'ja', id: 'healing_waltz' }); run(0.1);
ok(P().hp > ph && P().tp === 200, 'Healing Waltz heals for 200 TP');
G.save.jobsUnlocked.SCH = true; G.save.jobs.SCH.lv = 15; G.giveItem('ash_staff', 1, true); G.setJob('SCH', null); G.equip('ash_staff'); G.refreshPlayer(true); P().mp = P().maxMp;
const ids = G.actionList(P()).map(a => a.id);
ok(ids.includes('cure') && ids.includes('fire') && ids.includes('light_arts'), 'Scholars know cures, nukes and the arts');
G.playerAct({ kind: 'ja', id: 'dark_arts' }); run(0.1);
G.playerAct({ kind: 'ja', id: 'light_arts' }); run(0.1);
ok(P().buffs.light_arts && !P().buffs.dark_arts, 'Light Arts replaces Dark Arts');
G.playerAct({ kind: 'ja', id: 'penury' }); run(0.1);
P().hp = Math.floor(P().maxHp / 2); const mp0 = P().mp; P().target = P();
G.playerAct({ kind: 'ma', id: 'cure' }); run(3);
ok(P().mp === mp0 && !P().buffs.penury, 'Penury makes the next cure free');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
