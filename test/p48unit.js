read('scroll_banish');
ok(!G.save.spells.includes('banish'), 'main job below the spell level cannot learn it');
G.save.jobs.WHM.lv = 5; G.setJob('WHM', null);
read('scroll_banish');
ok(G.save.spells.includes('banish'), 'main job at the spell level learns it');
