let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const read = id => { G.S.itemReadyAt = 0; G.giveItem(id, 1, true); G.useItem(id); };
G.save.supportUnlocked = true;
G.save.spells = G.save.spells.filter(i => i !== 'banish');
G.save.jobs.WHM.lv = 20; G.save.jobs.WAR.lv = 8; G.setJob('WAR', null);
read('scroll_banish');
ok(!G.save.spells.includes('banish'), 'a White Mage scroll cannot be read as a Warrior, even with a levelled White Mage');
G.setJob('WAR', 'WHM');
ok(P().sub === 'WHM' && P().lv === 8, 'Warrior 8 with White Mage support');
read('scroll_banish');
