const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player; G.save.story.done = true;
G.save.spells = Object.keys(G.SPELLS);
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id) || G.meet(id);
const opt = re => S.dialog && S.dialog.all.find(o => re.test(o.label));

ok(G.CONFIG.levelCap >= 15 && G.CONFIG.xpTable.length === G.CONFIG.levelCap, 'level cap has an XP table to match');
G.save.jobs.BLM.lv = 10; G.setJob('BLM', null); G.gainXp(4450);
ok(P().lv === 11, 'a Dark Mage gains level 11');
G.gainXp(1e6);
ok(P().lv === G.CONFIG.levelCap && G.actionList(P()).some(a => a.id === 'sleep') && G.actionList(P()).some(a => a.id === 'drain'), 'XP stops at the level cap, with Life Leech and Sleep learned');
const ex = G.ZONES.hollow_lake.exits.find(e => e.to === 'marsh');
ok(ex && G.ZONES.marsh.exits.some(e => e.to === 'hollow_lake'), 'Rocky Hollow and the Ashen Marsh connect both ways');
G.enterZone('hollow_lake', ex.x + ex.w / 2, ex.y - 40); S.zoneCooldown = 0; P().y = ex.y + 4; run(0.5);
ok(S.zoneId === 'marsh', 'walking through the south exit enters the marsh');
run(1);
const fams = new Set(G.ZONES.marsh.spawns.flatMap(s => [s].concat(s.alts || [])).filter(o => o.time !== 'night').map(o => o.fam));
ok(['bog_toad', 'bog_leech', 'mire_goblin'].every(f => fams.has(f)), 'the marsh spawns toads, leeches and mire goblins by day (' + [...fams].join(',') + ')');
ok(S.mobs.every(m => m.lv >= 9), 'marsh monsters are level 9 and up');
let minD = 1e9; const sp = G.ZONES.marsh.spawns; for (let i = 0; i < sp.length; i++) for (let j = i + 1; j < sp.length; j++) minD = Math.min(minD, Math.hypot(sp[i].x - sp[j].x, sp[i].y - sp[j].y));
ok(minD >= 115, 'marsh spawn points are spread out (' + Math.round(minD) + ')');
ok(S.npcs.filter(n => n.prop === 'gather').length === 9, 'the marsh has 9 gathering points');
const toadFam = G.FAMILIES.bog_toad;
ok(toadFam.aggro && toadFam.aggro.sound, 'bog toads hunt by sound');
const hare = S.mobs.find(m => m.famKey === 'marsh_hare');
ok(!hare || hare.passive, 'reed hares are peaceful');
G.enterZone('outpost'); run(0.5);
G.TALK.talkRhea ? 0 : 0;
G.talkTo(npc('rhea'));
const ask = opt(/Into the Mire/);
ok(!!ask, 'Captain Rhea offers Into the Mire at level 10+');
ask.fn(); opt(/^Accept$/).fn();
ok(G.save.quests.mire === 'active', 'the quest can be accepted');
G.enterZone('marsh'); run(0.3);
for (let i = 0; i < 6; i++) { const m = G.buildMob('bog_toad', 11, P().x + 50, P().y, 0); S.mobs.push(m); m.enmity.set(P(), 5); G.onKO(m, P()); }
G.enterZone('outpost'); run(0.3); G.talkTo(npc('rhea'));
const rep = opt(/Into the Mire|Report/); rep.fn(); opt(/Collect/).fn();
ok(G.save.quests.mire === 'done' && G.invCount('bounding_boots') === 1, 'reporting back pays out Marsh Boots');
ok(G.ITEMS.spatha && G.ITEMS.gelong_staff && G.ITEMS.brass_harness, 'level 11 gear exists');
G.save.spells = G.save.spells.filter(i => i !== 'banish'); G.save.jobs.WHM.lv = 6; G.setJob('WHM', null);
ok(!G.actionList(P()).some(a => a.id === 'banish'), 'a spell is not known until its scroll is read');
G.giveItem('scroll_banish', 1, true); G.S.itemReadyAt = 0; G.useItem('scroll_banish');
ok(G.save.spells.includes('banish') && G.actionList(P()).some(a => a.id === 'banish') && G.invCount('scroll_banish') === 0, 'reading a scroll teaches the spell');
G.save.spells = G.save.spells.filter(i => i !== 'fire'); G.giveItem('scroll_fire', 1, true); G.save.jobs.BLM.lv = 5; G.useItem('scroll_fire');
ok(!G.save.spells.includes('fire') && G.invCount('scroll_fire') === 1, 'scrolls for spells above your level cannot be read yet');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
