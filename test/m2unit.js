const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const setLv = lv => { G.save.jobs[G.save.mainJob].lv = lv; G.refreshPlayer(true); };
G.enterZone('outpost'); run(0.3);
G.save.gil = 1e6;
setLv(10);
const pool = G.mercPool();
const gid = pool[0];
const f10 = G.mercFee(gid);
setLv(30);
ok(G.mercFee(gid) > f10, 'a daily mercenary\'s fee follows your current level');
G.hireMerc(gid);
const gm = S.party.find(p => p.mercId === gid);
ok(gm && gm.lv === 30 && G.save.mercHireLv[gid] === 30, 'mercenaries are hired at your level');
const plain = Object.values(G.autoGear(G.MERCS[gid].job, 30, G.MERCS[gid].role));
ok(plain.length && plain.every(id => !G.ITEMS[id].hq && G.GEAR_DATA[id].src === 'shop' && !/\+1/.test(G.ITEMS[id].name)), 'starting gear is plain shop gear, no +1 or named pieces');
G.hireMerc('kael');
const kael = () => S.party.find(p => p.mercId === 'kael');
const axe = Object.keys(G.ITEMS).filter(id => G.ITEMS[id].kind === 'equip' && G.ITEMS[id].slot === 'main' && G.ITEMS[id].jobs.includes(G.MERCS.kael.job) && G.ITEMS[id].lv >= 12 && G.ITEMS[id].lv <= 30).sort((a, b) => G.gearScore(b) - G.gearScore(a))[0];
G.mercBag('kael').length = 0;
G.save.mercGear.kael = { main: axe };
G.refreshPlayer(false);
ok(kael().gear.main === axe, 'Kael wears his level ' + G.ITEMS[axe].lv + ' weapon at level 30');
const att30 = kael().stats.att;
setLv(10);
ok(kael().lv === 10, 'mercenaries sync down with your level');
ok(!G.save.mercGear.kael.main && G.mercBag('kael').some(x => x.id === axe && !x.sale), 'gear above the new level moves to kept items');
ok(kael().gear.main && G.ITEMS[kael().gear.main].lv <= 10, 'a plain level-appropriate weapon fills the slot');
G.mercBag('kael').push(...Array.from({ length: 16 }, () => ({ id: 'bronze_dagger', qty: 1, sale: true })));
const S0 = S.zone.theme; S.zone.theme = 'town'; G.mercTownSell(); S.zone.theme = S0;
ok(G.mercBag('kael').length === 1 && G.mercBag('kael')[0].id === axe, 'town sell-off never sells kept items');
setLv(30);
ok(G.save.mercGear.kael.main === axe && !G.mercBag('kael').some(x => x.id === axe), 'kept gear goes back on when the level allows');
ok(kael().stats.att === att30, 'stats return to the same values after syncing back up');
const fresh = G.mercGearFor(gid, 30), mine = P().stats;
ok(gm.stats.att > mine.att * 0.5 && gm.stats.att < mine.att * 2 && gm.stats.def > mine.def * 0.5 && gm.stats.def < mine.def * 2, 'balance: a level 30 hire is within 2x of your attack and defence (merc ' + gm.stats.att + '/' + gm.stats.def + ', you ' + mine.att + '/' + mine.def + ')');
for (const lv of [1, 10, 20, 40, 60]) { setLv(lv); const k = kael(); ok(k.stats.maxHp > 0 && k.stats.att > 0 && k.lv === lv, 'balance at level ' + lv + ': HP ' + k.stats.maxHp + ', attack ' + k.stats.att + ', defence ' + k.stats.def + ' (you ' + P().stats.maxHp + '/' + P().stats.att + '/' + P().stats.def + ')'); }
setLv(30);
const fam = Object.keys(G.BESTIARY)[0];
delete G.save.bestiary[fam];
G.noteBeast({ famKey: fam, name: 'x' }, false);
ok(!G.save.bestiary[fam], 'seeing a creature does not add it to the bestiary');
G.noteBeast({ famKey: fam, name: 'x' }, true);
ok(G.save.bestiary[fam] && G.save.bestiary[fam].kills === 1, 'defeating one adds it');
const sv = JSON.parse(JSON.stringify(G.save)); sv.bestiary.zz = { seen: 1, kills: 0, zones: [] };
ok(!G.normalizeSave(sv).bestiary.zz, 'old seen-only entries are removed on load');
console.log(fails ? fails + ' FAILED' : 'ALL PASS'); process.exit(fails ? 1 : 0);
