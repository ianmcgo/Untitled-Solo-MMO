const H = require('./harness.js'); const { G, tick } = H; const S = G.S;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
G.enterZone('hollow'); run(0.5);
G.save.gil = 1e5; G.save.jobs[G.save.mainJob].lv = 20; G.refreshPlayer(true);
G.hireMerc('kael');
const fill = (id, item, n) => { const b = G.mercBag(id); b.length = 0; for (let i = 0; i < n; i++) b.push({ id: item, qty: 1, sale: true }); };
global.NET = {}; global.UI = global.UI || {};
let calls = [];
global.netMissing = e => /PGRST202/.test(String(e && e.code));
global.netMarketOnline = () => NET.market !== false;
global.netMercConsign = id => { calls.push(id); return Promise.resolve({ listed: 16, gone: 0 }).then(d => { G.save.mercInv[id] = G.save.mercInv[id].filter(x => !x.sale); return d; }); };
fill('kael', 'bat_wing', 16);
G.enterZone('outpost'); run(0.5);
(async () => {
  await new Promise(r => setTimeout(r, 20));
  ok(calls.length === 1 && calls[0] === 'kael', 'online, a companion\'s sell-off goes to the server consign call');
  ok(G.mercLotCount() === 0 && G.mercBag('kael').length === 0, 'online lots are not also kept in the offline list');
  global.netMercConsign = id => { calls.push(id); return Promise.reject({ code: 'PGRST202', message: 'Could not find the function' }); };
  fill('kael', 'bat_wing', 16);
  G.enterZone('hollow'); run(0.2); G.enterZone('outpost'); run(0.2);
  await new Promise(r => setTimeout(r, 20));
  ok(NET.market === false && G.mercLotCount() === 16 && G.mercBag('kael').length === 0, 'when the server has not been updated, it falls back to the offline list');
  fill('kael', 'bat_wing', 16); calls = [];
  G.enterZone('hollow'); run(0.2); G.enterZone('outpost'); run(0.2);
  ok(!calls.length && G.mercLotCount() === 32, 'after a fallback it stays offline for the session');
  const L = G.marketLocal(); L.lots.push({ id: 'bat_wing', qty: 1, price: 50, kind: 'town', seller: 'Ashenreach', owner: '', town: 'outpost', seq: 999 });
  const lines = G.marketLines('bat_wing', [{ id: 77, item: 'bat_wing', qty: 2, price: 60, kind: 'town', seller: null, seller_name: 'Saltreach', town: G.ahHere() }, { id: 78, item: 'bat_wing', qty: 1, price: 30, kind: 'merc', seller: 'me', seller_name: 'Tessa', merc_name: 'Dorn' }]);
  const rel = lines.find(l => l.kind === 'town' && l.local != null), on = lines.find(l => l.lot === 77), stock = lines.find(l => l.stock);
  ok(rel && !rel.stock && on && !on.stock && on.seller === 'Saltreach', 'relisted town lots are bought as lots, not from the town stock');
  ok(!stock || stock.kind === 'town', 'town stock lines are marked as stock');
  ok(lines.some(l => l.lot === 78 && l.kind === 'merc' && l.seller === 'Dorn' && l.owner === 'Tessa'), 'online companion lots show the companion\'s name, with the owner in the tooltip');
  console.log(fails ? fails + ' FAILED' : 'ALL PASS');
  process.exit(fails ? 1 : 0);
})();
