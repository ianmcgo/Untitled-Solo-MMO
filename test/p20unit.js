const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id) || G.meet(id);
const clickThrough = () => { for (let k = 0; k < 10 && S.dialog; k++) S.dialog.all[0].fn(); };
G.enterZone('outpost'); run(0.2);
ok(G.STORY.length === 8 && G.storyStep().npc === 'rhea', 'the story begins with Captain Rhea');
G.save.jobs.WAR.lv = 2; G.refreshPlayer(true);
G.talkTo(npc('rhea')); ok(!(S.dialog && /Ash has been falling/.test(S.dialog.text)), 'the story waits until level 3');
G.closeDialog && G.closeDialog();
G.save.jobs.WAR.lv = 3; G.refreshPlayer(true);
G.talkTo(npc('rhea')); ok(S.dialog && /Ash has been falling/.test(S.dialog.text), 'at level 3 Rhea tells you about the ash');
clickThrough();
ok(G.storyStep().type === 'visit' && G.storyStep().lm === 'fort', 'next: search the Old Fort Ruins');
const fort = G.ZONES.hollow_ruins.landmarks.find(l => l.id === 'fort');
