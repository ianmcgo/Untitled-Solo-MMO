const H = require('./harness.js'); const { G, tick } = H; const S = G.S; const P = () => G.player;
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const run = sec => { for (let i = 0; i < sec * 60; i++) tick(1000 / 60); };
const npc = id => S.npcs.find(n => n.id === id) || G.meet(id);
const opt = re => S.dialog && S.dialog.all.find(o => re.test(o.label));

G.enterZone('outpost'); run(0.2);
for (const j in G.JOBS) G.save.jobsUnlocked[j] = true;
G.save.jobs.WAR.lv = 6; G.refreshPlayer(true);
G.talkTo(npc('tobin'));
ok(!!opt(/Light Fingers/) && !!opt(/Open Hand/), 'Tobin offers the Thief and Monk quests at level 6');
opt(/Light Fingers/).fn(); opt(/^Accept$/).fn();
G.giveItem('goblin_pouch', 3, true); G.giveItem('bat_wing', 1, true);
G.talkTo(npc('tobin')); opt(/Light Fingers/).fn(); opt(/Collect/).fn();
ok(G.save.jobsUnlocked.THF && G.invCount('bronze_dagger') === 1, 'Light Fingers unlocks Thief and gives a dagger');
G.setJob('THF', null); G.equip('bronze_dagger');
ok(P().job === 'THF' && P().stats.wtype === 'dagger' && P().delay < 2, 'a Thief fights with a quick dagger');
G.enterZone('hollow', 300, 1100); run(0.3);
const m = G.buildMob('goblin', 3, P().x + 30, P().y, 0); S.mobs.push(m);
P().target = m;
const saved = Math.random; Math.random = () => 0.01;
G.playerAct({ kind: 'ja', id: 'steal' });
ok(m.stolen && ['goblin_pouch', 'fire_crystal', 'copper_ore', 'potion'].some(i => G.invCount(i) > 0), 'Pilfer lifts an item from the monster');
Math.random = saved;
P().buffs.sneak_attack = { until: S.time + 30 };
const hp0 = m.hp; G.toggleEngage(); for (let i = 0; i < 300 && m.hp === hp0; i++) tick(16);
ok(m.hp < hp0 && !P().buffs.sneak_attack && H.alllog.some(l => /critical/.test(l)), 'Shadow Strike makes the next hit a critical');
G.save.jobs.THF.lv = 10; G.refreshPlayer(true);
ok(G.actionList(P()).some(a => a.id === 'flee'), 'Thieves learn Fleet Foot at 10');
G.save.jobsUnlocked.MNK = true; G.save.jobs.MNK.lv = 10; G.setJob('MNK', null); G.giveItem('cesti', 1, true); G.equip('cesti');
ok(P().stats.wtype === 'h2h' && P().delay <= 2.1 && P().stats.dmg >= 11, 'Martial Arts speeds up and strengthens Monk fists (' + P().delay + 's, ' + P().stats.dmg + ')');
P().hp = 20; G.playerAct({ kind: 'ja', id: 'chakra' });
ok(P().hp > 100, 'Inner Mend restores a big chunk of HP');
G.save.gil = 9000; G.enterZone('outpost'); run(0.2);
G.hireMerc('wren'); G.hireMerc('tamsin');
ok(G.save.hired.includes('wren') === !!G.save.jobsUnlocked.THF && G.save.hired.includes('tamsin'), 'Wren and Tamsin join once their jobs are unlocked');
ok(G.ITEMS.brass_knuckles && G.ITEMS.dagger && G.ITEMS.kenpogi, 'Thief and Monk gear exists');
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
